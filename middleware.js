// Atlas gate (Vercel Routing Middleware). Runs before every request, static files included.
// No valid atlas_access cookie -> redirect to /activate.html. Non-payers never receive app
// pages, scripts-data.js or the companion pack PDFs.
import { next } from '@vercel/functions';
import { readCookie } from './lib/tokens.js';
import { storeReady, getStatus } from './lib/store.js';

// Public: the front door, referral pages, and the shared shell they need to render.
const PUBLIC = new Set([
  '/activate', '/activate.html', '/buy', '/buy/demo', '/buy/gift',
  '/demo',
  '/property', // Settlement Brief: free property settlement organiser (28 Oct 2026)
  '/terms', '/terms.html',
  '/how-it-works', '/how-it-works.html',
  '/for-professionals', '/for-professionals.html',
  '/favicon.svg', '/apple-touch-icon.png', '/robots.txt',
  // Free sales tool: the user guide (linked from how-it-works; /user-guide is a short link for Ghost).
  '/assets/Atlas - User guide.pdf', '/user-guide',
  // Supporter door (14 Oct 2026): free Supporter Guide and the printable gift card. Short links for Ghost.
  '/assets/Atlas - Supporter guide.pdf', '/supporter-guide',
  '/assets/Atlas - Gift card.pdf', '/gift-card',
  '/assets/app/bento.css', '/assets/app/interface.css', '/assets/app/app.js',
]);
// /demo/ is generated by demo-build (fictional data only, no gated files). Keep it in step with scripts/build-demo.mjs.
const PUBLIC_PREFIX = ['/api/', '/assets/fonts/', '/demo/', '/property/'];

export default async function middleware(request) {
  const url = new URL(request.url);
  let path = url.pathname;
  try { path = decodeURIComponent(path); } catch (_) { /* malformed: leave encoded, so it's gated */ }
  // A path that climbs out of a public folder (e.g. /demo/..%2fmoney.html) is never public.
  const climbs = path.includes('..') || path.includes('\\');
  if (!climbs && (PUBLIC.has(path) || PUBLIC_PREFIX.some(p => path.startsWith(p)))) return next();

  const cookie = /(?:^|;\s*)atlas_access=([^;]+)/.exec(request.headers.get('cookie') || '')?.[1];
  let access = { ok: false, id: null };
  try {
    if (cookie) access = await readCookie(cookie, (process.env.SESSION_SECRET || '').trim());
  } catch (_) { /* missing secret: fail closed */ }

  if (access.ok) {
    // Revoked keys (refunds, leaks) are locked out on every device. Checked on page loads only,
    // so assets stay fast. If the key list is unreachable, let paying customers through.
    const isPage = path === '/' || path.endsWith('.html');
    if (access.id && isPage && storeReady()) {
      try {
        if (await getStatus(access.id) === 'revoked') {
          return new Response(null, {
            status: 302,
            headers: {
              Location: new URL('/activate.html?revoked=1', url).toString(),
              'Set-Cookie': 'atlas_access=; Path=/; Max-Age=0; HttpOnly; Secure; SameSite=Lax',
            },
          });
        }
      } catch (_) { /* fail open */ }
    }
    return next();
  }

  const gate = new URL('/activate.html', url);
  // Send people back to the page they asked for once they're in (HTML pages only).
  if (path !== '/' && path.endsWith('.html')) gate.searchParams.set('next', url.pathname + url.search);
  return Response.redirect(gate, 302);
}
